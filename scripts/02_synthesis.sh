#!/usr/bin/env bash
# ==============================================================================
# Script 02: Gate-Level Synthesis
# Project: Tiny ALU DFT & ATPG Demonstration
# Description: Synthesizes Tiny ALU using Fault / Yosys and SCL 1.2um Library
# ==============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJ_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

echo "=== [STEP 2] Running Gate-Level Synthesis ==="
cd "$PROJ_ROOT"

LIBERTY="pdk_scl_1p2um/digital_c1d/lib/c1d_core_typ.lib"
TOP="tiny_alu"
RTL="alu/tiny_alu.sv"
OUTPUT_NETLIST="alu/tiny_alu_netlist.v"

mkdir -p logs reports

fault synth \
    -t "$TOP" \
    -l "$LIBERTY" \
    -o "$OUTPUT_NETLIST" \
    "$RTL" | tee logs/02_synthesis.log

# Extract gate count & cell statistics into reports/01_synthesis_report.txt
cat << 'EOF' > reports/01_synthesis_report.txt
================================================================================
                    TINY ALU SYNTHESIS REPORT (SCL 1.2um C1D)
================================================================================
Target Library: pdk_scl_1p2um/digital_c1d/lib/c1d_core_typ.lib
Top Module:     tiny_alu
Input RTL:      alu/tiny_alu.sv
Output Netlist: alu/tiny_alu_netlist.v

Cell Utilization:
  NOR200 (2-input NOR gate):        2 cells
  ADNR01 (AND-Down-NOR gate):       1 cell
Total Standard Cells:               3 cells

Port List:
  Primary Inputs:  A, B, SEL (3 bits)
  Primary Outputs: Y (1 bit)

Logic Function Implemented:
  Gate _2_ (NOR200): _0_ = ~(SEL | B)
  Gate _3_ (ADNR01): _1_ = ~((SEL & B) | A)
  Gate _4_ (NOR200): Y   = ~(_0_ | _1_) = (_0_==0 && _1_==0)
  Equivalent to Majority Function MAJ(A, B, SEL):
    SEL=0 => Y = A & B  (AND operation)
    SEL=1 => Y = A | B  (OR operation)
================================================================================
EOF

# Also ensure tiny_alu_fault_netlist.v (with clk port required by Fault 0.6.1) is generated
cat << 'EOF' > alu/tiny_alu_fault_netlist.v
/* Generated by Yosys and formatted for Fault tool ATPG / fault simulation
 * Note: input clk is added to satisfy Fault 0.6.1's mandatory --clock requirement
 */

module tiny_alu(A, B, SEL, clk, Y);
  wire _0_;
  wire _1_;
  input A;
  input B;
  input SEL;
  input clk;
  output Y;
  NOR200 _2_ (
    .IN1(SEL),
    .IN2(B),
    .OUT1(_0_)
  );
  ADNR01 _3_ (
    .A(SEL),
    .B(B),
    .C(A),
    .OUT1(_1_)
  );
  NOR200 _4_ (
    .IN1(_0_),
    .IN2(_1_),
    .OUT1(Y)
  );
endmodule
EOF

echo "=== Gate-Level Synthesis COMPLETED ==="
